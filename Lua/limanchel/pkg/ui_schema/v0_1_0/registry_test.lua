local busted = require("busted")
local assert = require("luassert")
local registry = require("limanchel.pkg.ui_schema.v0_1_0.registry")
local describe, it = busted.describe, busted.it

describe("Независимые регистрации", function()
   it("не разделяет изменяемые регистрации", function()
      local first, second = registry.new(), registry.new()
      first:register_enum("Mode", { On = 1 })
      assert.is_nil(second:get_enum("Mode"))
      assert.are.equal(1, first:get_enum("Mode").On)
      assert.has_error(function()
         first:register_enum("Mode", {})
      end)
   end)

   it("проверяет описания и имена", function()
      local reg = registry.new()
      assert.has_error(function()
         reg:register_type("", {})
      end)
      assert.has_error(function()
         reg:register_type("Panel", {})
      end)
      assert.has_error(function()
         reg:register_value_type("Value", false)
      end)
   end)
end)

local passed = 0
---@param label string
---@param body fun()
local function check(label, body)
   body()
   passed = passed + 1
   print("PASS " .. label)
end

for _, name in ipairs({ "BridgeProbes.Point", "BridgeProbes.Box", "BridgeProbes.Api" }) do
   LuaUserData.RegisterType(name)
end
local Box = LuaUserData.CreateStatic("BridgeProbes.Box")
local Api = LuaUserData.CreateStatic("BridgeProbes.Api")
local Point = LuaUserData.CreateStatic("BridgeProbes.Point")

check("constructors, fields, static, inheritance, interface", function()
   local box = Box()
   box.Number = 2
   assert(Box.__new().Name == "box" and box.Number == 2 and Box.StaticNumber == 8)
   assert(box.BaseName == "base" and Api.Name(box) == "box")
   assert(not pcall(function() return Box.init() end))
   assert(not pcall(function() return Box.new() end))
end)
check("readonly and private setter reject writes", function()
   local box = Box()
   assert(not pcall(function() box.Readonly = 1 end))
   assert(not pcall(function() box.ReadOnlyProperty = 1 end))
   assert(not pcall(function() box.PrivateSetter = 1 end))
end)
check("struct copy and explicit writeback", function()
   local box = Box()
   local point = Point()
   point.X = 3
   box.Position = point
   local copy = box.Position
   copy.X = 7
   assert(box.Position.X == 3)
   box.Position = copy
   Api.Move(copy)
   assert(box.Position.X == 7 and copy.X == 7)
end)
check("nil, optional, nullable", function()
   assert(Api.Optional() == 7 and Api.Optional(nil) == 7)
   assert(Api.OptionalText() == "default" and Api.OptionalText(nil) == nil)
   assert(Api.Nullable(nil) == nil and Api.Nullable(3) == 3)
   assert(not pcall(function() return Api.Integer(nil) end))
end)
check("number overload and rounding", function()
   assert(Api.Pick(3) == "double")
   assert(Api.Integer(2.5) == 2 and Api.Integer(3.5) == 4)
   assert(not pcall(function() return Api.Integer("3") end))
end)
check("params and ref/out", function()
   assert(Api.Sum(2, 3) == 5)
   local ret, number, label = Api.RefOut(3)
   assert(ret == 9 and number == 5 and label == "out")
   assert(not pcall(function() return Api.Sum({ 2, 3 }) end))
end)
check("table collections and no automatic DTO mapping", function()
   assert(Api.ListSum({ 2, 3 }) == 5 and Api.DictionaryValue({ a = 7 }) == 7)
   assert(Api.ObjectType({ a = 1 }) == "MoonSharp.Interpreter.Table")
   local DemoApi = LuaUserData.CreateStatic("BridgeDemo.Api")
   assert(not pcall(function() return DemoApi.Process({ Lines = {} }) end))
end)
check("unregistered list is table snapshot", function()
   local values = Api.List()
   assert(type(values) == "table" and values[1] == 10)
   values[1] = 99
   assert(Api.List()[1] == 10)
end)
check("registered list is zero-based userdata", function()
   LuaUserData.RegisterType("System.Collections.Generic.List`1[System.Int32]")
   local values = Api.List()
   assert(type(values) == "userdata" and values[0] == 10)
   values[0] = 15
   values:Add(30)
   assert(values.Count == 3 and Api.ListSum(values) == 65)
   local total = 0
   for value in values do total = total + value end
   assert(total == 65)
end)
check("explicit array wrapper and params", function()
   local descriptor = LuaUserData.RegisterType("System.Int32")
   local values = LuaUserData.CreateUserDataFromType({ 2, 3 }, descriptor.Type:MakeArrayType())
   assert(type(values) == "userdata" and values[0] == 2 and Api.Sum(values) == 5)
end)
check("enum numeric then registered", function()
   assert(Api.EnumEcho(2) == 2)
   LuaUserData.RegisterType("BridgeProbes.Mode")
   local Mode = LuaUserData.CreateStatic("BridgeProbes.Mode")
   assert(Api.EnumEcho(Mode.Two) == Mode.Two)
end)
check("generic explicit type and constraints", function()
   assert(Api.Echo(Box, Box()).Name == "box")
   assert(Api.Echo(Point, Point()).X == 0)
   assert(not pcall(function() return Api.Constrained(Point, Point()) end))
end)
check("Closure automatic, arbitrary Func needs converter", function()
   assert(Api.CallClosure(function(value) return value + 1 end) == 5)
   assert(not pcall(function() return Api.CallFunc(function(value) return value + 1 end) end))
end)
check("callback error propagates synchronously", function()
   assert(not pcall(function() return Api.CallClosure(function() error("callback-error") end) end))
end)
check("event signature limitation", function()
   assert(not pcall(function() Box().UnsupportedEvent.add(function() end) end))
end)
check("private member opt-in through real LuaCs service", function()
   local descriptor = LuaUserData.RegisterType("BridgeProbes.Box")
   local box = Box()
   assert(not pcall(function() return box.secret end))
   LuaUserData.MakeFieldAccessible(descriptor, "secret")
   LuaUserData.MakeMethodAccessible(descriptor, "Hidden", { "System.Int32" })
   LuaUserData.MakePropertyAccessible(descriptor, "PrivateSetter")
   box.secret = 20
   box.PrivateSetter = 21
   assert(box:Hidden(2) == 22 and box.PrivateSetter == 21)
end)
check("C# exceptions become pcall error strings", function()
   local ok, err = pcall(function() Api.Fail() end)
   assert(not ok and type(err) == "string" and string.find(err, "probe-error", 1, true))
end)
check("class reference and copied table container", function()
   local Request = LuaUserData.CreateStatic("BridgeDemo.Request")
   local Line = LuaUserData.CreateStatic("BridgeDemo.Line")
   local request = Request()
   local line = Line("a", 2)
   local input = { line }
   request.Lines = input
   input[1] = Line("b", 4)
   line.Quantity = 7
   assert(request.Lines[0].Name == "a" and request.Lines[0].Quantity == 7)
end)
check("generic numeric argument is not converted after MakeGenericMethod", function()
   local Int32 = LuaUserData.CreateStatic("System.Int32")
   assert(not pcall(function() return Api.Echo(Int32, 3) end))
end)
check("adapter rejects fractional quantity", function()
   local DemoApi = LuaUserData.CreateStatic("BridgeDemo.Api")
   assert(not pcall(function() return DemoApi.LineFromTable({ name = "a", quantity = 2.5 }) end))
end)
print("Bridge probes PASS: " .. passed)
